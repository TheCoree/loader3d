/**
 * The public documents: the privacy policy (152-ФЗ) and the user agreement (a public offer). Payment
 * providers and the bank require both to be reachable from every page, so the footer links here.
 * Who runs the service and the support contacts come from lib/legal.ts.
 */
export function LegalPage({ doc }: { doc: LegalDoc }) {
  const { title, body } = DOCS[doc];
  useEffect(() => {
    const previous = document.title;
    document.title = `${title} — Loader3D`;
    window.scrollTo(0, 0);
    return () => {
      document.title = previous;
    };
  }, [title]);

  return (
    <div className="min-h-dvh bg-white text-ink antialiased selection:bg-primary/25">
      <header className="sticky top-0 z-40 border-b border-white/[0.07] bg-ink/90 text-white backdrop-blur-xl backdrop-saturate-150">
        <div className="mx-auto flex h-16 w-full max-w-[1200px] items-center justify-between px-5 sm:px-8">
          <Logo />
          <Link
            to="/"
            className="inline-flex items-center gap-1.5 rounded-full px-3 py-1.5 text-sm text-white/65 transition-colors hover:bg-white/10 hover:text-white"
          >
            <ArrowLeft className="size-3.5" /> На главную
          </Link>
        </div>
      </header>

      <main className="mx-auto w-full max-w-[760px] px-5 pt-16 pb-24 sm:px-8 sm:pt-24 sm:pb-32">
        <h1 className={cn(displayTitle, 'text-[2rem] leading-[1.08] sm:text-[2.6rem]')}>{title}</h1>
        <p className="mt-4 text-[15px] text-ink/50">Редакция от {DOCS_DATE}</p>
        <nav aria-label="Документы" className="mt-8 flex flex-wrap gap-2">
          {(Object.keys(DOCS) as LegalDoc[]).map((d) => (
            <Link
              key={d}
              to={`/${d}`}
              aria-current={d === doc ? 'page' : undefined}
              className={cn(
                'rounded-full px-4 py-2 text-sm transition-colors',
                d === doc ? 'bg-ink text-white' : 'bg-[#f4f4f6] text-ink/65 hover:bg-[#ececef] hover:text-ink',
              )}
            >
              {DOCS[d].title}
            </Link>
          ))}
        </nav>
        <div className="mt-14 space-y-12">{body}</div>
      </main>

      <SiteFooter />
    </div>
  );
}

