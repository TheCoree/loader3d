/** The three «how many pallets fit» pages: a semi-trailer, a container, a Gazelle. Numbers come from core/tools. */

function preset(id: string) {
  return VEHICLE_PRESETS.find((p) => p.id === id)!;
}

function body(id: string, label: string): BodyChoice {
  const b = preset(id).bodies[0];
  return { id, label, dims: b.dims, maxLoad: b.maxLoad ?? 0, kind: b.kind, chassisModel: b.chassisModel };
}

const m = (cm: number) => num(cm / 100, 2);
const m3 = (d: Dims) => num((d.l * d.w * d.h) / 1e6, 1);
const dimsText = (d: Dims) => `${m(d.l)} × ${m(d.w)} × ${m(d.h)} м`;

/** Floor places of the standard pallets on a deck, along only and at best. */
function deck(d: { l: number; w: number }) {
  return {
    eurAlong: gridFit(d, PALLETS.eur, false).count,
    eurTurned: gridFit(d, PALLETS.eur, true).count,
    eur: bestFit(d, PALLETS.eur).count,
    fin: bestFit(d, PALLETS.fin).count,
  };
}

const link = (id: Parameters<typeof toolPage>[0], text: string) => <Link to={toolPage(id).path}>{text}</Link>;

